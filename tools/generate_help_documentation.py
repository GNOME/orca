def _add_command_item(parent: ET.Element, command: CollectedCommandDoc) -> ET.Element | None:
    """Adds one command item."""

    if command.command_type == "braille":
        if not command.braille_bindings:
            return None

        item = _append_child(parent, "item")
        p = _append_child(item, "p")
        gui = _append_child(p, "gui", command.label)
        gui.tail = f": {', '.join(command.braille_bindings)}"
        _add_since_notice(item, command.since)
        return item

    if command.command_type != "keyboard":
        return None

    item = _append_child(parent, "item")
    p = _append_child(item, "p")
    gui = _append_child(p, "gui", command.label)
    details = []
    if command.summary:
        details.append(_sentence(command.summary))
    if command.details:
        details.append(_sentence(command.details))
    gui.tail = _gui_description_tail(command.label, " ".join(details)) if details else ""
    _add_since_notice(item, command.since)

    desktop = command.desktop_keybinding
    laptop = command.laptop_keybinding
    if desktop is None and laptop is None:
        gui.tail = f"{gui.tail} Unbound by default."
        return item

    if _keybindings_equal(desktop, laptop):
        assert desktop is not None
        gui.tail = f"{gui.tail} "
        _append_keyseq(p, desktop)
        return item

    binding_list = _append_child(item, "list")
    _add_command_binding_item(binding_list, "Desktop", desktop)
    _add_command_binding_item(binding_list, "Laptop", laptop)
    return item


def _command_matches_section(command: CollectedCommandDoc, section: CommandSectionDoc) -> bool:
    """Returns True if command belongs in section."""

    if section.command_types and command.command_type not in section.command_types:
        return False
    if not section.command_names and not section.command_prefixes:
        return True
    if command.name in section.command_names:
        return True
    return any(command.name.startswith(prefix) for prefix in section.command_prefixes)


def _command_section_sort_key(
    command: CollectedCommandDoc,
    section: CommandSectionDoc,
) -> tuple[int, int, str]:
    """Returns a sort key based on command order in section metadata."""

    try:
        return (0, section.command_names.index(command.name), command.label.casefold())
    except ValueError:
        pass

    for index, prefix in enumerate(section.command_prefixes):
        if command.name.startswith(prefix):
            return (1, index, command.label.casefold())

    return (2, 0, command.label.casefold())


def _command_link_title(group: CollectedCommandGroupDoc) -> str:
    """Returns the command group's link title."""

    if group.link_title:
        return group.link_title
    return f"{group.title} commands"


def _command_destination_key(command: CollectedCommandDoc) -> str:
    """Returns an internal registry key that distinguishes keyboard and braille commands."""

    return f"command:{command.command_type}:{command.name}"


def _command_content_registry(
    groups: list[tuple[str, CollectedCommandGroupDoc]],
) -> dict[str, CollectedCommandGroupDoc]:
    """Indexes reusable command groups and their named subsections."""

    contents: dict[str, CollectedCommandGroupDoc] = {}
    for page_id, group in groups:
        aliases = (page_id, f"commands.{_target_page_id(page_id, COMMANDS_PAGE_PREFIX)}")
        for alias in (*aliases, group.target):
            if alias:
                contents[alias] = group
        for section in group.sections:
            selected = copy.copy(group)
            selected.commands = sorted(
                (
                    command
                    for command in group.commands
                    if _command_matches_section(command, section)
                ),
                key=partial(_command_section_sort_key, section=section),
            )
            selected.title = section.title
            selected.sections = ()
            selected.summary = section.summary
            selected.since = section.since or group.since
            section_id = _id_fragment(section.title)
            for alias in (section.target, f"{aliases[1]}.{section_id}", f"{page_id}#{section_id}"):
                if alias:
                    contents[alias] = selected
    return contents


def _feature_command_targets(
    page_docs: list[FeaturePageDoc],
    reusable_sections: dict[str, FeatureSectionDoc],
    groups: list[tuple[str, CollectedCommandGroupDoc]],
) -> dict[str, str]:
    """Assigns every command to exactly one topic and redirects old command targets."""

    contents = _command_content_registry(groups)
    commands = {
        command.name: command
        for _page_id, group in groups
        for command in group.commands
        if command.command_type == "keyboard"
    }
    targets: dict[str, str] = {}
    explicit: set[str] = set()
    sections: list[tuple[str, FeatureSectionDoc]] = []

    def assign(command: CollectedCommandDoc, destination: str) -> None:
        key = _command_destination_key(command)
        if key in targets:
            raise ValueError(f"Command {key} is included more than once")
        targets[key] = destination

    for page in page_docs:
        resolved_sections = _resolve_feature_sections(page, reusable_sections)
        for section in resolved_sections:
            destination = (
                _feature_section_page_id(page, section)
                if page.sections_as_pages
                else page.page_id
                if len(resolved_sections) == 1 and section.title == page.title
                else f"{page.page_id}#{_id_fragment(section.title)}"
            )
            sections.append((destination, section))
    for destination, section in sections:
        for name in section.command_names:
            if name not in commands:
                raise ValueError(f"Unknown feature command {name!r}")
            explicit.add(name)
            assign(commands[name], destination)

    for destination, section in sections:
        for reference in section.command_groups:
            if reference not in contents:
                raise ValueError(f"Unknown feature command group {reference!r}")
            command_destination = (
                f"{destination.split('#', 1)[0]}"
                f"#{_id_fragment(f'commands-{contents[reference].title}')}"
            )
            for command in contents[reference].commands:
                if command.command_type == "keyboard" and command.name in explicit:
                    continue
                assign(command, command_destination)

    for reference, content in contents.items():
        destinations = [
            targets.get(_command_destination_key(command)) for command in content.commands
        ]
        if any(destination is None for destination in destinations):
            missing = [
                c.name for c in content.commands if _command_destination_key(c) not in targets
            ]
            raise ValueError(f"Commands without a feature topic in {reference}: {missing}")
        if destinations:
            first_destination = destinations[0]
            assert first_destination is not None
            targets[reference] = first_destination
    return targets


def _preference_command_links(
    page_docs: list[PageDoc],
    groups: list[tuple[str, CollectedCommandGroupDoc]],
    targets: dict[str, str],
    link_text: dict[str, LinkTextDoc],
) -> PreferenceCommandLinks:
    """Resolves provider-declared associations using actual command placements."""

    contents = _command_content_registry(groups)
    commands = {
        command.name: command
        for _page_id, group in groups
        for command in group.commands
        if command.command_type == "keyboard"
    }
    by_panel: dict[str, tuple[tuple[str, str], ...]] = {}
    by_command: dict[str, dict[str, str]] = {}
    for page in page_docs:
        for panel in page.panels:
            category = _target_page_id(page.page_id, PREFERENCES_PAGE_PREFIX)
            destination = targets.get(
                f"preferences.{category}.{panel.panel_id.rsplit('.', 1)[-1]}", page.page_id
            )
            label = _preferences_link_title(panel.title)
            links: dict[str, str] = {}
            selected: list[tuple[CollectedCommandDoc, str]] = []
            for reference in panel.command_groups:
                if reference not in contents or reference not in link_text:
                    raise ValueError(f"Unknown preference command group: {reference!r}")
                content = contents[reference]
                group_destination = targets[reference]
                group_label = link_text[reference].label
                selected.extend(
                    (command, group_label)
                    for command in content.commands
                    if targets[_command_destination_key(command)] == group_destination
                )
            for name in panel.command_names:
                if name not in commands:
                    raise ValueError(f"Unknown preference command: {name!r}")
                selected.append((commands[name], commands[name].label))
            for command, command_label in selected:
                key = _command_destination_key(command)
                if key not in targets:
                    raise ValueError(f"No help destination for command {command.name!r}")
                links.setdefault(targets[key], command_label)
                by_command.setdefault(key, {})[destination] = label
            by_panel[panel.panel_id] = tuple(links.items())
    return PreferenceCommandLinks(
        by_panel=by_panel,
        by_command={key: tuple(links.items()) for key, links in by_command.items()},
    )


def _add_reference_sentence(
    parent: ET.Element, prefix: str, links: tuple[tuple[str, str], ...]
) -> None:
    """Adds a short, non-bulleted cross-reference without repeating destinations."""

    if not links:
        return
    paragraph = _append_child(parent, "p", prefix)
    for index, (destination, label) in enumerate(links):
        link = _append_child(paragraph, "link", label)
        link.set("xref", destination)
        link.tail = "." if index == len(links) - 1 else ", "


def _add_command_type_lists(parent: ET.Element, commands: list[CollectedCommandDoc]) -> None:
    """Keeps keyboard and braille-display bindings distinct within a shared command topic."""

    mixed = len({command.command_type for command in commands}) > 1
    for command_type, title in (
        ("keyboard", "Standard keyboard commands"),
        ("braille", "Braille display commands"),
    ):
        selected = [command for command in commands if command.command_type == command_type]
        if not selected:
            continue
        container = parent
        if mixed:
            container = _append_child(parent, "section")
            container.set("id", f"{parent.attrib['id']}-{command_type}")
            _append_child(container, "title", title)
        command_list = _append_child(container, "list")
        for command in selected:
            _add_command_item(command_list, command)


def _add_feature_command_group(
    parent: ET.Element,
    group: CollectedCommandGroupDoc,
    commands: list[CollectedCommandDoc],
    title: str = "Commands",
    preferences_page: PageDoc | None = None,
    show_location: bool = True,
) -> None:
    """Embeds command documentation, retaining subsections and braille bindings."""

    if not commands:
        return
    section = _append_child(parent, "section")
    section.set("id", _id_fragment(f"commands-{group.title}"))
    _append_child(section, "title", title)
    _add_since_notice(section, group.since)
    if preferences_page and show_location:
        _add_command_preferences_location(section, commands, preferences_page)
    if not group.sections:
        _add_command_type_lists(section, commands)
        return

    section_commands: list[list[CollectedCommandDoc]] = [[] for _ in group.sections]
    for command in commands:
        matches = [
            index
            for index, subsection in enumerate(group.sections)
            if _command_matches_section(command, subsection)
        ]
        if len(matches) != 1:
            raise ValueError(
                f"Command {command.name!r} in {group.title!r} matches "
                f"{len(matches)} command sections; expected exactly one"
            )
        section_commands[matches[0]].append(command)
    for subsection, selected in zip(group.sections, section_commands, strict=True):
        selected.sort(key=partial(_command_section_sort_key, section=subsection))
        if not selected:
            continue
        container = section
        if subsection.title != "Commands":
            container = _append_child(section, "section")
            container.set("id", _id_fragment(f"{group.title}-{subsection.title}"))
            _append_child(container, "title", subsection.title)
        if subsection.since != group.since:
            _add_since_notice(container, subsection.since)
        command_list = _append_child(container, "list")
        for command in selected:
            _add_command_item(command_list, command)


def _section_preference_panels(
    section: FeatureSectionDoc,
    pages: dict[str, PageDoc],
    panels: dict[str, tuple[PageDoc, PanelDoc]],
) -> list[tuple[PageDoc, PanelDoc]]:
    """Resolves category and individual-panel references without copying settings metadata."""

    if not section.preference_categories and not section.preference_panels:
        return []
    selected: list[tuple[PageDoc, PanelDoc]] = []
    for category in section.preference_categories:
        if category not in pages:
            raise ValueError(f"Unknown feature preference category: {category!r}")
        selected.extend((pages[category], panel) for panel in pages[category].panels)
    for panel_id in section.preference_panels:
        if panel_id not in panels:
            raise ValueError(f"Unknown feature preference panel: {panel_id!r}")
        selected.append(panels[panel_id])
    return selected


def _settings_anchor(section: FeatureSectionDoc, panel: PanelDoc | None = None) -> str:
    """Uses stable section/panel names for settings anchors."""

    name = f"settings-{section.title}"
    if panel:
        name += f"-{panel.panel_id}"
    return _id_fragment(name)


def _feature_preference_placements(
    feature_pages: list[FeaturePageDoc],
    reusable_sections: dict[str, FeatureSectionDoc],
    preference_pages: list[PageDoc],
) -> dict[str, str]:
    """Assigns settings panels to feature topics, rejecting duplicate placements."""

    categories = {
        _target_page_id(page.page_id, PREFERENCES_PAGE_PREFIX): page for page in preference_pages
    }
    panels = {panel.panel_id: (page, panel) for page in preference_pages for panel in page.panels}
    placements: dict[str, str] = {}
    for feature in feature_pages:
        sections = [
            (
                section,
                _feature_section_page_id(feature, section)
                if feature.sections_as_pages
                else feature.page_id,
            )
            for section in _resolve_feature_sections(feature, reusable_sections)
        ]
        if feature.preference_panels:
            sections.append(
                (
                    FeatureSectionDoc(
                        title=feature.title,
                        preference_panels=feature.preference_panels,
                    ),
                    feature.page_id,
                )
            )
        for section, page_id in sections:
            selected = _section_preference_panels(section, categories, panels)
            for _category, panel in selected:
                if panel.panel_id in placements:
                    raise ValueError(f"Duplicate feature preference panel: {panel.panel_id!r}")
                anchor = _settings_anchor(section, panel if len(selected) > 1 else None)
                placements[panel.panel_id] = f"{page_id}#{anchor}"
        if feature.preference_category:
            if feature.preference_category not in categories:
                raise ValueError(
                    f"Unknown feature preference category: {feature.preference_category!r}"
                )
            for panel in categories[feature.preference_category].panels:
                if _id_fragment(panel.title) == _id_fragment(
                    categories[feature.preference_category].link_title
                ):
                    if any(control.control_type != "page" for control in panel.controls):
                        continue
                    if panel.panel_id in placements:
                        raise ValueError(f"Duplicate feature preference panel: {panel.panel_id!r}")
                    placements[panel.panel_id] = feature.page_id
    return placements


def _preference_target_registry(
    page_docs: list[PageDoc],
    feature_pages: list[FeaturePageDoc] | None = None,
    reusable_sections: dict[str, FeatureSectionDoc] | None = None,
) -> dict[str, str]:
    """Returns logical preference targets mapped to generated Mallard xrefs."""

    placements = _feature_preference_placements(
        feature_pages or [], reusable_sections or {}, page_docs
    )
    missing = {
        panel.panel_id
        for page in page_docs
        for panel in page.panels
        if panel.panel_id not in placements
    }
    if feature_pages is not None and missing:
        raise ValueError(f"Preference panels without a feature topic: {sorted(missing)}")
    guides = {
        page.preference_category: page.page_id
        for page in feature_pages or []
        if page.preference_category
    }
    targets: dict[str, str] = {}
    for page_doc in page_docs:
        category = _target_page_id(page_doc.page_id, PREFERENCES_PAGE_PREFIX)
        page_target = f"preferences.{category}"
        destinations = {
            placements[panel.panel_id].split("#", 1)[0]
            for panel in page_doc.panels
            if panel.panel_id in placements
        }
        if destinations and any(panel.panel_id not in placements for panel in page_doc.panels):
            raise ValueError(f"Unplaced preference panels in {category!r}")
        if len(destinations) > 1 and category not in guides:
            raise ValueError(f"Split preference category needs a guide: {category!r}")
        destination = guides.get(category) or next(iter(destinations), page_doc.page_id)
        targets[page_target] = destination
        targets[page_doc.page_id] = destination
        section_ids = _panel_section_ids(page_doc.panels)
        for panel in page_doc.panels:
            if panel.category and panel.category.target:
                if panel.category.target in targets:
                    raise ValueError(f"Duplicate preference target: {panel.category.target}")
                targets[panel.category.target] = destination
            panel_xref = page_doc.page_id
            if _id_fragment(panel.title) != _id_fragment(page_doc.link_title):
                panel_xref += f"#{section_ids[panel.title]}"
            old_xref = panel_xref
            panel_xref = placements.get(panel.panel_id, panel_xref)
            if old_xref != page_doc.page_id:
                targets[old_xref] = panel_xref
            if panel.target:
                targets[panel.target] = panel_xref
            targets[f"{page_target}.{_id_fragment(panel.title)}"] = panel_xref
            targets[f"{page_target}.{panel.panel_id.rsplit('.', 1)[-1]}"] = panel_xref
    return targets


def _preferences_link_title(title: str) -> str:
    """Qualifies a preference link without repeating an existing qualifier."""

    return title if title.casefold().endswith("preferences") else f"{title} preferences"


def _preference_link_text_registry(page_docs: list[PageDoc]) -> dict[str, LinkTextDoc]:
    """Returns default link text for preference targets."""

    link_text: dict[str, LinkTextDoc] = {}
