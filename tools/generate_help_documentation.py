def _source_module(name: str, namespace: dict[str, Any]) -> types.ModuleType:
    """Constructs an importable module from an explicit namespace."""

    module = types.ModuleType(name)
    module.__dict__.update(namespace)
    return module


@contextlib.contextmanager
def _temporary_modules(modules: dict[str, types.ModuleType]) -> Any:
    """Restores the import table after evaluating trusted source definitions."""

    saved = {name: sys.modules.get(name) for name in modules}
    sys.modules.update(modules)
    try:
        yield
    finally:
        for name, module in saved.items():
            if module is None:
                sys.modules.pop(name, None)
            else:
                sys.modules[name] = module


