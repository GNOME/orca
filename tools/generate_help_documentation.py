def _target_page_id(page_id: str, prefix: str) -> str:
    """Returns page_id without a generated-page prefix."""

    return page_id.removeprefix(f"{prefix}_").replace("_", "-")


def _call_name(node: ast.Call) -> str | None:
    """Returns the simple function name for a Call node."""

    func = node.func
    if isinstance(func, ast.Name):
        return func.id
    if isinstance(func, ast.Attribute):
        return func.attr
    return None


def _is_named_call(node: ast.AST, name: str) -> bool:
    """Returns True if node calls name as a bare or qualified function."""

    return isinstance(node, ast.Call) and _call_name(node) == name


def _find_keyword(node: ast.Call, name: str) -> ast.AST | None:
    """Returns a named or positional metadata argument."""

    names = _PREFERENCE_FIELDS.get(_call_name(node) or "")
    if names is not None:
        if len(node.args) > len(names):
            raise ValueError(f"Too many arguments to {_call_name(node)} at line {node.lineno}")
        unknown = {item.arg for item in node.keywords if item.arg is not None} - set(names)
        if unknown:
            raise ValueError(f"Unknown {_call_name(node)} fields: {sorted(unknown)}")
        duplicates = set(names[: len(node.args)]) & {item.arg for item in node.keywords}
        if duplicates:
            raise ValueError(f"Duplicate {_call_name(node)} fields: {sorted(duplicates)}")
        if name in names and names.index(name) < len(node.args):
            return node.args[names.index(name)]
    for keyword in node.keywords:
        if keyword.arg == name:
            return keyword.value
    return None


