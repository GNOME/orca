def _collect_user_visible_constants(path: Path) -> dict[str, str]:
    """Extracts translated string constants from path."""

    tree = ast.parse(path.read_text(encoding="utf-8"))
    labels: dict[str, str] = {}
    module_constants: dict[str, Any] = {}
    evaluator = SourceEvaluator(
        labels={},
        class_constants={},
        module_constants=module_constants,
    )

    for node in tree.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if not isinstance(target, ast.Name):
            continue
        value = evaluator.eval(node.value)
        if isinstance(value, str):
            value = _strip_mnemonic(value)
            labels[target.id] = value
            module_constants[target.id] = value

    return labels


def _collect_constants(
    src_dir: Path,
    labels: dict[str, str] | None = None,
) -> tuple[dict[str, dict[str, Any]], dict[str, dict[str, Any]]]:
    """Collects module and class constants from src/orca/*.py."""

    labels = labels or {}
    all_class_constants: dict[str, dict[str, Any]] = {}
    all_module_constants: dict[str, dict[str, Any]] = {}

    for path in sorted((src_dir / "orca").glob("*.py")):
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except (OSError, SyntaxError):
            continue

        module_constants: dict[str, Any] = {}
        evaluator = SourceEvaluator(
            labels=labels, class_constants=all_class_constants, module_constants={}
        )

        for node in tree.body:
            if isinstance(node, ast.Assign) and len(node.targets) == 1:
                target = node.targets[0]
                if isinstance(target, ast.Name):
                    value = evaluator.eval(node.value)
                    if isinstance(value, (str, int, float, bool)):
                        module_constants[target.id] = value
            elif isinstance(node, ast.ClassDef):
                constants = all_class_constants.setdefault(node.name, {})
                local_evaluator = SourceEvaluator(
                    labels=labels,
                    class_constants=all_class_constants,
                    module_constants=module_constants,
                )
                for stmt in node.body:
                    if not isinstance(stmt, ast.Assign) or len(stmt.targets) != 1:
                        continue
                    target = stmt.targets[0]
                    if isinstance(target, ast.Name):
                        value = local_evaluator.eval(stmt.value)
                        if isinstance(value, (str, int, float, bool)):
                            constants[target.id] = value

        all_module_constants[path.name] = module_constants

    return all_class_constants, all_module_constants


def _is_auto_preferences_grid(class_node: ast.ClassDef) -> bool:
    """Returns True if class_node directly subclasses AutoPreferencesGrid."""

    for base in class_node.bases:
        if isinstance(base, ast.Name) and base.id == "AutoPreferencesGrid":
            return True
        if isinstance(base, ast.Attribute) and base.attr == "AutoPreferencesGrid":
            return True
    return False


def _find_init(class_node: ast.ClassDef) -> ast.FunctionDef | None:
    """Returns class_node.__init__, if present."""

    for item in class_node.body:
        if isinstance(item, ast.FunctionDef) and item.name == "__init__":
            return item
    return None


def _class_schema(class_node: ast.ClassDef, evaluator: SourceEvaluator) -> str:
    """Returns the _gsettings_schema class attribute, if present."""

    for item in class_node.body:
        if not isinstance(item, ast.Assign) or len(item.targets) != 1:
            continue
        target = item.targets[0]
        if isinstance(target, ast.Name) and target.id == "_gsettings_schema":
            value = evaluator.eval(item.value)
            return value if isinstance(value, str) else ""
    return ""


def _panel_title(init_node: ast.FunctionDef, evaluator: SourceEvaluator) -> str:
    """Returns the tab label passed to AutoPreferencesGrid.__init__."""

    for node in ast.walk(init_node):
        if not isinstance(node, ast.Call):
            continue
        if not isinstance(node.func, ast.Attribute) or node.func.attr != "__init__":
            continue
        if node.args:
            value = evaluator.eval(node.args[0])
            if isinstance(value, str):
                return _strip_mnemonic(value)
    return ""


def _extract_control(
    node: ast.Call,
    evaluator: SourceEvaluator,
    settings: dict[tuple[str, str], SettingDoc],
    settings_by_key: dict[str, list[SettingDoc]],
    schema: str,
    source_file: str,
) -> ControlDoc | None:
    """Extracts one preference control call into documentation metadata."""

    call_name = _call_name(node)
    if call_name not in CONTROL_TYPES:
        return None

    label = evaluator.eval(_find_keyword(node, "label"))
    if not isinstance(label, str) or not label:
        return None

    key_value = evaluator.eval(_find_keyword(node, "prefs_key"))
    key = key_value if isinstance(key_value, str) else ""
    effective_schema = schema
    if not effective_schema and key:
        matching_settings = settings_by_key.get(key, [])
        if len(matching_settings) == 1:
            effective_schema = matching_settings[0].schema_name

    options_value = evaluator.eval(_find_keyword(node, "options"))
    options: list[str] = []
    dynamic_options = False
    if isinstance(options_value, list):
        options = [str(option) for option in options_value if option is not None]
        dynamic_options = any(option is None for option in options_value)
    elif _find_keyword(node, "options") is not None:
        dynamic_options = True

    minimum = evaluator.eval(_find_keyword(node, "minimum"))
    maximum = evaluator.eval(_find_keyword(node, "maximum"))

    setting = settings.get((effective_schema, key)) if effective_schema and key else None
    return ControlDoc(
        label=_strip_mnemonic(label),
        control_type=CONTROL_TYPES[call_name],
        schema=effective_schema,
        key=key,
        summary=setting.summary if setting else "",
        default=setting.default if setting else "",
        type_info=setting.type_info if setting else "",
        options=options,
        minimum="" if minimum is None else str(minimum),
        maximum="" if maximum is None else str(maximum),
        dynamic_options=dynamic_options,
        source_file=source_file,
        source_line=node.lineno,
    )


def _is_preferences_grid(class_node: ast.ClassDef) -> bool:
    """Returns True if class_node directly subclasses a preferences grid base class."""

    for base in class_node.bases:
        if isinstance(base, ast.Name) and base.id == "PreferencesGridBase":
            return True
        if isinstance(base, ast.Attribute) and base.attr == "PreferencesGridBase":
            return True
        if isinstance(base, ast.Name) and base.id == "AutoPreferencesGrid":
            return True
        if isinstance(base, ast.Attribute) and base.attr == "AutoPreferencesGrid":
            return True
    return False


def _find_documentation_method(class_node: ast.ClassDef) -> ast.FunctionDef | None:
    """Returns class_node.get_documentation(), if present."""

    for item in class_node.body:
        if isinstance(item, ast.FunctionDef) and item.name == "get_documentation":
            return item
    return None


def _returned_panel_doc(method_node: ast.FunctionDef) -> ast.Call | None:
    """Returns the PreferencePanelDoc call returned by a documentation method."""

    for node in ast.walk(method_node):
        if isinstance(node, ast.Return) and isinstance(node.value, ast.Call):
            if not _is_named_call(node.value, "PreferencePanelDoc"):
                continue
            return node.value
    return None


def _extract_doc_control(
    node: ast.Call,
    evaluator: SourceEvaluator,
    settings: dict[tuple[str, str], SettingDoc],
    source_file: str,
) -> ControlDoc | None:
    """Extracts one PreferenceControlDoc call into generator metadata."""

    if not _is_named_call(node, "PreferenceControlDoc"):
        return None

    label = evaluator.eval(_find_keyword(node, "label"))
    control_type = evaluator.eval(_find_keyword(node, "kind"))
    if not isinstance(label, str) or not label or not isinstance(control_type, str):
        raise ValueError(f"Cannot read preference control at {source_file}:{node.lineno}")
    if control_type not in get_args(_HELP_METADATA.PreferenceKind):
        raise ValueError(f"Unknown preference kind {control_type!r} at {source_file}:{node.lineno}")

    schema = evaluator.eval(_find_keyword(node, "schema"))
    key = evaluator.eval(_find_keyword(node, "key"))
    target = evaluator.eval(_find_keyword(node, "target"))
    summary = evaluator.text(_find_keyword(node, "summary"))
    values = evaluator.eval(_find_keyword(node, "values"))
    value_docs_node = _find_keyword(node, "value_docs")
    default_labels_node = _find_keyword(node, "default_labels")
    actions_node = _find_keyword(node, "actions")
    item_actions_node = _find_keyword(node, "item_actions")
    controls_node = _find_keyword(node, "controls")
    dynamic_values = evaluator.eval(_find_keyword(node, "dynamic_values"))
    minimum = evaluator.eval(_find_keyword(node, "minimum"))
    maximum = evaluator.eval(_find_keyword(node, "maximum"))

    schema = schema if isinstance(schema, str) else ""
    key = key if isinstance(key, str) else ""
    setting = settings.get((schema, key)) if schema and key else None
    options = [str(value) for value in values] if isinstance(values, (tuple, list)) else []
    if schema and key and setting is None:
        raise ValueError(
            f"Unknown preference setting {schema}/{key} at {source_file}:{node.lineno}"
        )
    value_docs = _extract_doc_values(value_docs_node, evaluator) if value_docs_node else []
    actions = _extract_doc_actions(actions_node, evaluator) if actions_node else []
    item_actions = _extract_doc_actions(item_actions_node, evaluator) if item_actions_node else []
    controls: list[ControlDoc] = []
    if isinstance(controls_node, (ast.Tuple, ast.List)):
        for element in controls_node.elts:
            if not isinstance(element, ast.Call):
                continue
            control = _extract_doc_control(element, evaluator, settings, source_file)
            if control is not None:
                controls.append(control)

    return ControlDoc(
        label=_strip_mnemonic(label),
        control_type=control_type,
        schema=schema,
        key=key,
        target=target if isinstance(target, str) else "",
        summary=str(summary or (setting.summary if setting else "")),
        default=setting.default if setting else "",
        default_labels=(
            _extract_doc_values(default_labels_node, evaluator) if default_labels_node else []
        ),
        type_info=setting.type_info if setting else "",
        options=options,
        value_docs=value_docs,
        actions=actions,
        item_actions=item_actions,
        controls=controls,
        minimum="" if minimum is None else str(minimum),
        maximum="" if maximum is None else str(maximum),
        dynamic_options=bool(dynamic_values),
        source_file=source_file,
        source_line=node.lineno,
        since=evaluator.text(_find_keyword(node, "since")),
    )


def _extract_doc_actions(node: ast.AST, evaluator: SourceEvaluator) -> list[ActionDoc]:
    """Extracts PreferenceActionDoc calls into generator metadata."""

    if not isinstance(node, (ast.Tuple, ast.List)):
        return []

    actions: list[ActionDoc] = []
    for element in node.elts:
        if not isinstance(element, ast.Call) or not _is_named_call(element, "PreferenceActionDoc"):
            continue
        label = evaluator.eval(_find_keyword(element, "label"))
        summary = evaluator.text(_find_keyword(element, "summary"))
        placement = evaluator.eval(_find_keyword(element, "placement"))
        if not isinstance(label, str) or not label:
            continue
        actions.append(
            ActionDoc(
                label=_strip_mnemonic(label),
                summary=summary if isinstance(summary, str) else "",
                placement=placement if isinstance(placement, str) else "",
            )
        )
    return actions


def _extract_doc_values(node: ast.AST, evaluator: SourceEvaluator) -> list[ValueDoc]:
    """Extracts PreferenceValueDoc calls into generator metadata."""

    if not isinstance(node, (ast.Tuple, ast.List)):
        return []

    values: list[ValueDoc] = []
    for element in node.elts:
        if not isinstance(element, ast.Call) or not _is_named_call(element, "PreferenceValueDoc"):
            continue
        label = evaluator.eval(_find_keyword(element, "label"))
        value = evaluator.eval(_find_keyword(element, "value"))
        summary = evaluator.text(_find_keyword(element, "summary"))
        if not isinstance(label, str) or not label:
            continue
        values.append(
            ValueDoc(
                label=_strip_mnemonic(label),
                value=value if isinstance(value, str) else "",
                summary=summary if isinstance(summary, str) else "",
                since=evaluator.text(_find_keyword(element, "since")),
            )
        )
    return values


def _extract_category_doc(
    node: ast.AST | None, evaluator: SourceEvaluator
) -> PreferenceCategoryDoc | None:
    """Reads category metadata without loading a preferences window."""

    if node is None:
        return None
    if not isinstance(node, ast.Call) or not _is_named_call(node, "PreferenceCategoryDoc"):
        raise ValueError("A preference category must be a PreferenceCategoryDoc constructor")
    values = {
        item.name: evaluator.eval(value)
        for item in fields(PreferenceCategoryDoc)
        if (value := _find_keyword(node, item.name)) is not None
    }
    category = PreferenceCategoryDoc(**values)
    if not all(
        isinstance(value, str) and value.strip()
        for value in (category.category_id, category.title, category.description)
    ):
        raise ValueError("Preference categories need an id, title, and description")
    if not isinstance(category.panels, tuple) or not category.panels:
        raise ValueError(f"Preference category {category.category_id!r} needs panel ids")
    if not all(isinstance(panel, str) and panel for panel in category.panels):
        raise ValueError(f"Invalid panel ids in category {category.category_id!r}")
    if not isinstance(category.application_preferences, bool):
        raise ValueError(f"Invalid application availability in category {category.category_id!r}")
    if not isinstance(category.application_details, str):
        raise ValueError(f"Invalid application details in category {category.category_id!r}")
    if not isinstance(category.target, str):
        raise ValueError(f"Invalid feature metadata in category {category.category_id!r}")
    return category


def _extract_protocol_panel(
    class_node: ast.ClassDef,
    evaluator: SourceEvaluator,
    settings: dict[tuple[str, str], SettingDoc],
    source_file: str,
) -> PanelDoc | None:
    """Extracts protocol-backed documentation metadata from a preferences grid."""

    if not _is_preferences_grid(class_node):
        return None

    method_node = _find_documentation_method(class_node)
    if method_node is None:
        return None

    panel_call = _returned_panel_doc(method_node)
    if panel_call is None:
        return None

    title = evaluator.eval(_find_keyword(panel_call, "title"))
    if not isinstance(title, str) or not title:
        title = class_node.name

    panel_id = evaluator.eval(_find_keyword(panel_call, "panel_id"))
    if not isinstance(panel_id, str) or not panel_id:
        panel_id = _panel_id(source_file, title)

    schema = evaluator.eval(_find_keyword(panel_call, "schema"))
    target = evaluator.eval(_find_keyword(panel_call, "target"))
    instructions = evaluator.text(_find_keyword(panel_call, "instructions"))
    link_summary = evaluator.text(_find_keyword(panel_call, "link_summary"))
    show_available_settings = evaluator.eval(_find_keyword(panel_call, "show_available_settings"))
    controls_node = _find_keyword(panel_call, "controls")
    controls: list[ControlDoc] = []

    if isinstance(controls_node, (ast.Tuple, ast.List)):
        for element in controls_node.elts:
            if not isinstance(element, ast.Call):
                continue
            control = _extract_doc_control(element, evaluator, settings, source_file)
            if control is not None:
                controls.append(control)

    if not controls:
        return None

    return PanelDoc(
        panel_id=panel_id,
        title=_strip_mnemonic(title),
        schema=schema if isinstance(schema, str) else "",
        target=target if isinstance(target, str) else "",
        controls=controls,
        instructions=instructions,
        link_summary=str(link_summary or ""),
        show_available_settings=(
            show_available_settings if isinstance(show_available_settings, bool) else True
        ),
        source_file=source_file,
        source_line=class_node.lineno,
        category=_extract_category_doc(_find_keyword(panel_call, "category"), evaluator),
        command_groups=tuple(evaluator.eval(_find_keyword(panel_call, "command_groups")) or ()),
        command_names=tuple(evaluator.eval(_find_keyword(panel_call, "command_names")) or ()),
        since=evaluator.text(_find_keyword(panel_call, "since")),
    )


class _FakeCommandOwner(types.SimpleNamespace):
    """Owner object whose methods can be used as command callbacks."""

    def __init__(
        self,
        group_label: str,
        constants: dict[str, Any],
        methods: set[str],
        voice_set: tuple[str, str],
    ) -> None:
        callbacks = {
            name: _unused_callback
            for name in methods
            if name not in {"__init__", "get_available_voice_sets", "_voice_set_display_name"}
        }
        super().__init__(
            **{
                **callbacks,
                **constants,
                "GROUP_LABEL": group_label,
                "_suspended": False,
            }
        )
        self._voice_set_id, self._voice_set_label = voice_set

    def get_available_voice_sets(self) -> list[str]:
        """Returns voice sets known without reading user profile data."""

        return [self._voice_set_id]

    def _voice_set_display_name(self, set_id: str) -> str:
        """Returns a display name for a fake voice set."""

        if set_id == self._voice_set_id:
            return self._voice_set_label
        return set_id


def _unused_callback(*_args: Any, **_kwargs: Any) -> bool:
    """Provides callbacks and inactive state getters without invoking runtime code."""

    return False


def _source_keybindings() -> dict[str, Any]:
    """Loads binding definitions without importing desktop or device modules."""

    path = Path(__file__).resolve().parents[1] / "src/orca/keybindings.py"
    tree = ast.parse(path.read_text(encoding="utf-8"))
    definitions = [
        node
        for node in tree.body
        if (
            isinstance(node, ast.Assign)
            and all(isinstance(target, ast.Name) and target.id.isupper() for target in node.targets)
        )
        or (isinstance(node, ast.ClassDef) and node.name == "KeyBinding")
    ]
    # Modifier positions are part of the AT-SPI protocol; Orca masks come from source.
    namespace: dict[str, Any] = {
        "Atspi": types.SimpleNamespace(
            ModifierType=types.SimpleNamespace(SHIFT=0, CONTROL=2, ALT=3, META3=6)
        ),
    }
    module = ast.Module(
        body=[
            ast.ImportFrom(module="__future__", names=[ast.alias(name="annotations")], level=0),
            *definitions,
        ],
        type_ignores=[],
    )
    ast.fix_missing_locations(module)
    # pylint: disable-next=exec-used
    exec(compile(module, str(path), "exec"), namespace)  # noqa: S102
    return namespace


