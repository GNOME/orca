def _sentence(text: str) -> str:
    """Returns text with sentence capitalization and terminal punctuation."""

    text = text.strip()
    if not text:
        return ""
    text = text[:1].upper() + text[1:]
    if text[-1] not in ".?!":
        text += "."
    return text


def _first_sentence(text: str) -> str:
    """Returns the first paragraph sentence from text."""

    text = text.strip()
    if not text:
        return ""
    paragraph = text.split("\n\n", 1)[0].strip()
    match = re.search(r"(?<=[.?!])\s", paragraph)
    if match is not None:
        return paragraph[: match.start()].strip()
    return paragraph


def _format_default(default: str, type_info: str) -> str:
    """Returns a human-readable GSettings default."""

    if type_info == "b":
        if default == "true":
            return "on"
        if default == "false":
            return "off"
    if default.startswith("'") and default.endswith("'"):
        return default[1:-1] or "empty"
    return default


def _normalized_default(control: ControlDoc) -> str:
    """Returns the control default value normalized for display comparisons."""

    return _format_default(control.default, control.type_info)


def _is_default_value(control: ControlDoc, label: str, value: str = "") -> bool:
    """Returns True if label or value represents the control default."""

    default = _normalized_default(control)
    if not default:
        return False
    return default.casefold() in {label.casefold(), value.casefold()}


def _choice_labels(control: ControlDoc) -> list[str]:
    """Returns rendered choice labels, marking the default when it can be identified."""

    if control.value_docs:
        if any(value_doc.summary for value_doc in control.value_docs):
            return [value_doc.label for value_doc in control.value_docs]

        labels = []
        for value_doc in control.value_docs:
            label = value_doc.label
            if _is_default_value(control, value_doc.label, value_doc.value):
                label += " (default)"
            labels.append(label)
        return labels

    return [
        f"{option} (default)" if _is_default_value(control, option) else option
        for option in control.options
    ]


def _show_default(control: ControlDoc) -> bool:
    """Returns True if the default value is useful in end-user help."""

    if not control.default:
        return False
    if control.dynamic_options and control.control_type in {"choice", "list", "table"}:
        return False
    return not control.default.startswith("@")


def _add_since_notice(parent: ET.Element, since: str) -> None:
    """Adds the public release in which an item became available."""

    if since == "":
        return
    if not isinstance(since, str) or not re.fullmatch(r"[0-9]+", since):
        raise ValueError(f"Invalid Orca introduction release: {since!r}")
    note = _append_child(parent, "note")
    _append_child(note, "p", f"Available in Orca {since} and later.")


def _add_value_descriptions(parent: ET.Element, control: ControlDoc) -> None:
    """Adds descriptions for documented values."""

    if not any(value_doc.summary or value_doc.since for value_doc in control.value_docs):
        return

    value_docs = [
        value_doc
        for value_doc in control.value_docs
        if value_doc.summary
        or value_doc.since
        or _is_default_value(control, value_doc.label, value_doc.value)
    ]
    if not value_docs:
        return

    list_el = _append_child(parent, "list")
    for value_doc in value_docs:
        item = _append_child(list_el, "item")
        p = _append_child(item, "p")
        label = value_doc.label
        if _is_default_value(control, value_doc.label, value_doc.value):
            label += " (default)"
        gui = _append_child(p, "gui", label)
        if value_doc.summary:
            gui.tail = _gui_description_tail(label, _sentence(value_doc.summary))
        _add_since_notice(item, value_doc.since)


def _gui_description_tail(label: str, description: str) -> str:
    """Returns separator text after a gui element before its description."""

    if label.rstrip().endswith(":"):
        return f" {description}"
    return f": {description}"


def _add_action_descriptions(parent: ET.Element, control: ControlDoc) -> None:
    """Adds descriptions for per-item actions."""

    actions = [action for action in control.item_actions if action.summary]
    if not actions:
        return

    list_el = _append_child(parent, "list")
    for action in actions:
        item = _append_child(list_el, "item")
        p = _append_child(item, "p")
        gui = _append_child(p, "gui", action.label)
        gui.tail = _gui_description_tail(action.label, _sentence(action.summary))


def _add_action_item(parent: ET.Element, action: ActionDoc) -> ET.Element | None:
    """Adds an action as a top-level item."""

    if not action.summary:
        return None

    item = _append_child(parent, "item")
    p = _append_child(item, "p")
    gui = _append_child(p, "gui", action.label)
    gui.tail = _gui_description_tail(action.label, _sentence(action.summary))
    return item


def _add_text_paragraphs(parent: ET.Element, text: str) -> None:
    """Adds paragraphs or simple bullet lists from non-empty text blocks."""

    for paragraph in [part.strip() for part in text.split("\n\n")]:
        if paragraph:
            lines = paragraph.splitlines()
            if all(line.startswith("- ") for line in lines):
                list_el = _append_child(parent, "list")
                for line in lines:
                    item = _append_child(list_el, "item")
                    _append_paragraph_with_inline_markup(item, line[2:])
            else:
                _append_paragraph_with_inline_markup(parent, paragraph)


_KEY_LABEL_PATTERN = (
    r"Orca Modifier|Keypad Insert|Caps Lock|Shift Lock|Num Lock|Insert|"
    r"Page Up|Page Down|Left Arrow|Right Arrow|Up Arrow|Down Arrow|"
    r"Left|Right|Up|Down|"
    r"Backspace|Delete|Escape|Return|Enter|Shift|Ctrl|Alt|Super|Tab|Space|Home|End|Esc|"
    r"F(?:1[0-2]|[1-9])"
)
_KEY_SEQUENCE_PATTERN = re.compile(
    r"(?<![\w+])((?:Orca Modifier|Ctrl|Alt|Shift|Super)\+"
    r"(?:(?:Ctrl|Alt|Shift|Super)\+)*[A-Z]|"
    rf"({_KEY_LABEL_PATTERN})(?:\+({_KEY_LABEL_PATTERN}))*)"
    r"(?![\w+])"
)
_INLINE_PROSE_PATTERN = re.compile(r"`(?P<code>[^`\n]+)`|" + _KEY_SEQUENCE_PATTERN.pattern)


def _append_text(parent: ET.Element, child: ET.Element | None, text: str) -> None:
    """Appends text as parent text or as the tail of the most recent child."""

    if child is None:
        parent.text = (parent.text or "") + text
    else:
        child.tail = (child.tail or "") + text


def _append_inline_key_markup(parent: ET.Element, label: str) -> ET.Element:
    """Appends key or keyseq markup for a key label found in prose."""

    if "+" in label:
        keyseq = _append_child(parent, "keyseq")
        for key in label.split("+"):
            _append_child(keyseq, "key", key)
        return keyseq

    return _append_child(parent, "key", label)


def _append_paragraph_with_inline_markup(parent: ET.Element, text: str) -> ET.Element:
    """Adds a paragraph with inline code and recognized key names."""

    p = _append_child(parent, "p")
    last_index = 0
    child = None
    for match in _INLINE_PROSE_PATTERN.finditer(text):
        _append_text(p, child, text[last_index : match.start()])
        if match.group("code") is not None:
            child = _append_child(p, "code", match.group("code"))
        else:
            child = _append_inline_key_markup(p, match.group(0))
        last_index = match.end()

    _append_text(p, child, text[last_index:])
    return p


def _add_control_item(
    parent: ET.Element,
    control: ControlDoc,
) -> ET.Element | None:
    if control.control_type == "page":
        return None
    summary = _sentence(control.summary)

    behavior_parts = []
    choice_labels = _choice_labels(control)
    if choice_labels:
        behavior_parts.append("Choices: " + ", ".join(choice_labels))

    if _show_default(control) and (not choice_labels or control.default_labels):
        default = _format_default(control.default, control.type_info)
        for value in control.default_labels:
            if value.value == ("" if default == "empty" else default):
                default = value.label
                break
        behavior_parts.append(f"Default: {default}")
    if control.minimum or control.maximum:
        behavior_parts.append(f"Range: {control.minimum or '?'} to {control.maximum or '?'}")

    item = _append_child(parent, "item")
    p = _append_child(item, "p")
    gui = _append_child(p, "gui", control.label)
    detail_parts = [part for part in [summary, *behavior_parts] if part]
    if detail_parts:
        tail = _gui_description_tail(
            control.label,
            " ".join(_sentence(part) for part in detail_parts),
        )
        gui.tail = tail
    else:
        gui.tail = ""

    _add_since_notice(item, control.since)
    _add_value_descriptions(item, control)
    _add_action_descriptions(item, control)
    if control.controls:
        list_el = _append_child(item, "list")
        for child_control in control.controls:
            _add_control_item(list_el, child_control)
    return item


def _load_preferences_metadata(path: Path) -> dict[str, Any]:
    """Loads generated-help prose metadata."""

    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as error:
        raise ValueError(f"Help metadata file not found: {path}") from error


def _add_panel_contents(
    parent: ET.Element,
    panel: PanelDoc,
    command_links: tuple[tuple[str, str], ...] = (),
    *,
    show_availability: bool = True,
) -> None:
    """Adds the contents of one panel to an existing section."""

    _add_since_notice(parent, panel.since)
    if panel.instructions:
        _add_text_paragraphs(parent, panel.instructions)
    if panel.category:
        if show_availability and not panel.category.application_preferences:
            _add_text_paragraphs(
                parent, "These settings are available only in the global Preferences window."
            )
        if panel.category.application_details:
            _add_text_paragraphs(parent, panel.category.application_details)
    _add_reference_sentence(parent, "For commands, see ", command_links)
    controls = [control for control in panel.controls if control.control_type != "page"]
    if not controls:
        return
    if panel.show_available_settings:
        label = _append_child(_append_child(parent, "p"), "em", "Available settings:")
        label.set("style", "strong")

    list_el = _append_child(parent, "list")
    for control in controls:
        for action in [action for action in control.actions if action.placement == "header"]:
            _add_action_item(list_el, action)
        _add_control_item(list_el, control)

        for action in [action for action in control.actions if action.placement != "header"]:
            _add_action_item(list_el, action)


def _page_docs_from_groups(panels: list[PanelDoc], metadata: dict[str, Any]) -> list[PageDoc]:
    """Combines provider-owned categories with the central display order."""

    panels_by_id = {panel.panel_id: panel for panel in panels}
    if len(panels_by_id) != len(panels):
        raise ValueError("Duplicate preference panel id")
    categories: dict[str, PreferenceCategoryDoc] = {}
    for panel in panels:
        if panel.category is None:
            continue
        category = panel.category
        if category.category_id in categories:
            raise ValueError(f"Duplicate preference category: {category.category_id}")
        if panel.panel_id not in category.panels:
            raise ValueError(f"Category {category.category_id} does not include its owning panel")
        categories[category.category_id] = category

    order = metadata.get("preference_order")
    if not isinstance(order, list) or not all(isinstance(item, str) for item in order):
        raise ValueError("preference_order must be a list of category ids")
    if len(order) != len(set(order)):
        raise ValueError("Duplicate category in preference_order")
    missing = categories.keys() - set(order)
    unknown_categories = set(order) - categories.keys()
    if missing or unknown_categories:
        raise ValueError(
            f"Preference category inventory mismatch: missing={sorted(missing)}, "
            f"unknown={sorted(unknown_categories)}"
        )
    listed = [panel_id for category in categories.values() for panel_id in category.panels]
    unknown = set(listed) - panels_by_id.keys()
    unlisted = panels_by_id.keys() - set(listed)
    if len(listed) != len(set(listed)):
        raise ValueError("A preference panel is listed more than once")
    if unknown or unlisted:
        raise ValueError(
            f"Preference panel inventory mismatch: unknown={sorted(unknown)}, "
            f"unlisted={sorted(unlisted)}"
        )
    page_docs: list[PageDoc] = []
    seen_page_ids: set[str] = set()
    for index, category_id in enumerate(order, start=1):
        category = categories[category_id]
        title = category.title
        group_panels = [panels_by_id[panel_id] for panel_id in category.panels]

        page_id = _page_id(category_id)
        if page_id in seen_page_ids:
            raise ValueError(f"Duplicate preference page id: {page_id}")
        seen_page_ids.add(page_id)
        page_docs.append(
            PageDoc(
                page_id=page_id,
                filename=_page_filename(page_id),
                title=f"{title} Preferences",
                sort_title=f"{index:02d}. {title}",
                link_title=title,
                description=category.description,
                panels=group_panels,
                since=category.since,
            )
        )

    for page_doc, next_page_doc in itertools.pairwise(page_docs):
        page_doc.next_page_id = next_page_doc.page_id
    return page_docs


