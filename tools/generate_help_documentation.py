def _add_feature_preferences(
    parent: ET.Element,
    section: FeatureSectionDoc,
    context: FeatureCommandContext,
) -> None:
    """Embeds provider-owned settings and their Preferences directory entries."""

    selected = _section_preference_panels(
        section, context.preference_categories, context.preference_panels
    )
    if not selected:
        return
    settings = _append_child(parent, "section")
    settings.set("id", _settings_anchor(section))
    _append_child(settings, "title", "Settings")
    seen_categories = set()
    for preference_page, panel in selected:
        container = settings
        if len(selected) > 1:
            container = _append_child(settings, "section")
            container.set("id", _settings_anchor(section, panel))
            _append_child(container, "title", panel.title)
        category = next(panel.category for panel in preference_page.panels if panel.category)
        if category.category_id not in seen_categories:
            _add_since_notice(container, category.since)
            seen_categories.add(category.category_id)
        path: tuple[tuple[str, str], ...] = ((preference_page.link_title, "category"),)
        if _id_fragment(panel.title) != _id_fragment(preference_page.link_title):
            path += ((panel.title, "group"),)
        _add_preferences_location(
            container,
            path,
            global_only=not category.application_preferences,
        )
        _add_panel_contents(container, panel, show_availability=False)


def _add_named_feature_commands(
    parent: ET.Element,
    section: FeatureSectionDoc,
    commands_by_name: dict[str, CollectedCommandDoc],
    context: FeatureCommandContext,
    grouped: bool = False,
) -> None:
    """Renders an explicit command subset after any embedded settings."""

    if not section.command_names:
        return
    container = parent
    if not grouped:
        container = _append_child(parent, "section")
        container.set("id", _id_fragment(f"commands-{section.title}"))
        _append_child(container, "title", "Commands")
    commands = [commands_by_name[name] for name in section.command_names]
    preferences_page = context.preference_categories.get("commands")
    if preferences_page and not context.shared_command_location:
        _add_command_preferences_location(container, commands, preferences_page)
    command_list = _append_child(container, "list")
    for command in commands:
        _add_command_item(command_list, command)


def _add_feature_section_contents(
    parent: ET.Element,
    section_doc: FeatureSectionDoc,
    targets: dict[str, str],
    link_text: dict[str, LinkTextDoc],
    commands_by_name: dict[str, CollectedCommandDoc],
    command_context: FeatureCommandContext,
    page_id: str,
) -> None:
    """Adds the body of a feature documentation section."""

    _add_since_notice(parent, section_doc.since)
    if not section_doc.intro and not section_doc.details:
        for reference in section_doc.command_groups:
            _add_text_paragraphs(parent, command_context.contents[reference].summary)
    if section_doc.intro:
        _add_text_paragraphs(
            parent, _feature_prose(section_doc.intro, section_doc, commands_by_name)
        )
    if section_doc.details:
        _add_text_paragraphs(
            parent, _feature_prose(section_doc.details, section_doc, commands_by_name)
        )
    linked_preferences = {
        targets.get(link.target, link.target)
        for link in (*section_doc.settings_and_commands, *section_doc.links)
    }
    for reference in section_doc.command_groups:
        linked_preferences.update(
            targets.get(target, target) for target in command_context.contents[reference].see_also
        )
    preference_links: dict[str, str] = {}
    section_commands = []
    for name in section_doc.command_names:
        if name not in commands_by_name:
            raise ValueError(
                f"Feature section {section_doc.title!r} references unknown command {name!r}"
            )
        section_commands.append(commands_by_name[name])
    section_commands.extend(
        command
        for reference in section_doc.command_groups
        for command in command_context.contents[reference].commands
    )
    for command in section_commands:
        for destination, label in command_context.preference_links.by_command.get(
            _command_destination_key(command), ()
        ):
            if destination not in linked_preferences and destination.split("#", 1)[0] != page_id:
                preference_links.setdefault(destination, label)
    _add_reference_sentence(parent, "For related settings, see ", tuple(preference_links.items()))
    _add_feature_preferences(parent, section_doc, command_context)
    command_contents = command_context.contents
    groups = [
        (
            command_contents[reference],
            [
                c
                for c in command_contents[reference].commands
                if c.command_type != "keyboard" or c.name not in command_context.explicit_names
            ],
        )
        for reference in section_doc.command_groups
    ]
    groups = [(content, commands) for content, commands in groups if commands]
    grouped = len(groups) + bool(section_doc.command_names) > 1
    commands_parent = parent
    if grouped:
        commands_parent = _append_child(parent, "section")
        commands_parent.set("id", _id_fragment(f"{section_doc.title}-commands"))
        _append_child(commands_parent, "title", "Commands")
        labels = {commands_by_name[name].group for name in section_doc.command_names}
        labels.update(command.group for _content, commands in groups for command in commands)
        preferences = command_context.preference_categories.get("commands")
        if len(labels) == 1 and preferences and not command_context.shared_command_location:
            representative = (
                commands_by_name[section_doc.command_names[0]]
                if section_doc.command_names
                else groups[0][1][0]
            )
            _add_command_preferences_location(commands_parent, [representative], preferences)
            command_context = replace(command_context, shared_command_location=True)
    _add_named_feature_commands(
        commands_parent, section_doc, commands_by_name, command_context, grouped
    )
    for content, commands in groups:
        title = content.title if grouped else "Commands"
        _add_feature_command_group(
            commands_parent,
            content,
            commands,
            title,
            preferences_page=command_context.preference_categories.get("commands"),
            show_location=not command_context.shared_command_location,
        )

    if section_doc.after_commands:
        _add_text_paragraphs(
            parent, _feature_prose(section_doc.after_commands, section_doc, commands_by_name)
        )

    def related(links: tuple[FeatureLinkDoc, ...]) -> tuple[FeatureLinkDoc, ...]:
        result: list[FeatureLinkDoc] = []
        seen: set[str] = set()
        for link in links:
            destination = targets.get(link.target, link.target)
            if destination.split("#", 1)[0] == page_id or destination in seen:
                continue
            seen.add(destination)
            result.append(link)
        return tuple(result)

    group_links = tuple(
        FeatureLinkDoc(target)
        for reference in section_doc.command_groups
        for target in command_contents[reference].see_also
    )
    related_links = related((*section_doc.settings_and_commands, *section_doc.links, *group_links))
    links_parent = parent
    if (
        section_doc.command_groups
        or section_doc.command_names
        or section_doc.preference_categories
        or section_doc.preference_panels
    ) and related_links:
        links_parent = _append_child(parent, "section")
        links_parent.set("id", _id_fragment(f"{section_doc.title}-related"))
        _append_child(links_parent, "title", "Related topics")
    _add_feature_links(links_parent, related_links, targets, link_text, "See also:")


def _build_feature_section_page(
    page_doc: FeaturePageDoc,
    section_doc: FeatureSectionDoc,
    sort_index: int,
    targets: dict[str, str],
    link_text: dict[str, LinkTextDoc],
    commands_by_name: dict[str, CollectedCommandDoc],
    command_context: FeatureCommandContext,
) -> ET.ElementTree:
    """Builds one generated child topic for a feature section."""

    page = ET.Element(f"{{{MALLARD_NS}}}page")
    page.set("type", "topic")
    page.set("id", _feature_section_page_id(page_doc, section_doc))

    info = _append_child(page, "info")
    guide_link = _append_child(info, "link")
    guide_link.set("type", "guide")
    guide_link.set("xref", page_doc.topics_guide_xref or page_doc.page_id)
    sort_title = _append_child(info, "title", f"{sort_index:02d}. {section_doc.title}")
    sort_title.set("type", "sort")
    link_title = _append_child(info, "title", section_doc.title)
    link_title.set("type", "link")
    _append_child(info, "desc", _first_sentence(section_doc.intro or section_doc.details))
    _add_credit(info)
    _add_license(info)

    _append_child(page, "title", section_doc.title)
    if page_doc.since != section_doc.since:
        _add_since_notice(page, page_doc.since)
    _add_feature_section_contents(
        page,
        section_doc,
        targets,
        link_text,
        commands_by_name,
        command_context,
        _feature_section_page_id(page_doc, section_doc),
    )
    return ET.ElementTree(page)


def _add_feature_guide_links(
    parent: ET.Element,
    sections: tuple[FeatureSectionDoc, ...],
    page_doc: FeaturePageDoc,
    targets: dict[str, str],
) -> None:
    """Adds guide links for feature section child topics."""

    if not sections and not page_doc.topics:
        return

    links = _append_child(parent, "links")
    links.set("type", "topic")
    links.set("style", "2column")
    if page_doc.topics_title:
        _append_child(links, "title", page_doc.topics_title)
    info = parent.find(f"{{{MALLARD_NS}}}info")
    assert info is not None
    if page_doc.topics_guide_xref:
        # Keep the standalone guide usable when its topics belong to another guide.
        for section_doc in sections:
            topic_link = _append_child(info, "link")
            topic_link.set("type", "topic")
            topic_link.set("xref", _feature_section_page_id(page_doc, section_doc))
    for target in page_doc.topics:
        if target not in targets:
            raise ValueError(f"Unknown feature topic target: {target!r}")
        topic_link = _append_child(info, "link")
        topic_link.set("type", "topic")
        topic_link.set("xref", targets[target])


def _share_command_location(
    parent: ET.Element,
    sections: tuple[FeatureSectionDoc, ...],
    commands: dict[str, CollectedCommandDoc],
    context: FeatureCommandContext,
) -> FeatureCommandContext:
    """Shows a common command location once for multi-section feature topics."""

    command_sections = [
        section for section in sections if section.command_names or section.command_groups
    ]
    preferences = context.preference_categories.get("commands")
    if len(command_sections) < 2 or not preferences:
        return context
    selected = [commands[name] for section in command_sections for name in section.command_names]
    selected.extend(
        command
        for section in command_sections
        for reference in section.command_groups
        for command in context.contents[reference].commands
        if command.command_type == "keyboard" and command.name not in context.explicit_names
    )
    if len({command.group for command in selected}) != 1:
        return context
    _add_command_preferences_location(parent, selected, preferences)
    return replace(context, shared_command_location=True)


def _build_feature_page(
    page_doc: FeaturePageDoc,
    sort_index: int,
    targets: dict[str, str],
    link_text: dict[str, LinkTextDoc],
    reusable_sections: dict[str, FeatureSectionDoc],
    commands_by_name: dict[str, CollectedCommandDoc],
    command_context: FeatureCommandContext,
) -> ET.ElementTree:
    """Builds one generated feature Mallard page."""

    sections = _resolve_feature_sections(page_doc, reusable_sections)
    page = ET.Element(f"{{{MALLARD_NS}}}page")
    page.set("type", "guide" if page_doc.sections_as_pages else "topic")
    page.set("id", page_doc.page_id)

    info = _append_child(page, "info")
    if page_doc.guide_xref:
        guide_link = _append_child(info, "link")
        guide_link.set("type", "guide")
        guide_link.set("xref", page_doc.guide_xref)
    sort_title = _append_child(info, "title", f"{sort_index:02d}. {page_doc.title}")
    sort_title.set("type", "sort")
    link_title = _append_child(info, "title", page_doc.link_title)
    link_title.set("type", "link")
    _append_child(info, "desc", page_doc.description)
    _add_credit(info)
    _add_license(info)

    _append_orca_logo_feature_title(page, page_doc.title)
    _add_since_notice(page, page_doc.since)
    if page_doc.intro:
        _add_text_paragraphs(page, page_doc.intro)
    if page_doc.details:
        _add_text_paragraphs(page, page_doc.details)
    if page_doc.preference_panels:
        _add_feature_preferences(
            page,
            FeatureSectionDoc(title=page_doc.title, preference_panels=page_doc.preference_panels),
            command_context,
        )
    if page_doc.preference_category:
        category = command_context.preference_categories[page_doc.preference_category]
        _add_since_notice(page, category.since)
        for panel in category.panels:
            if _id_fragment(panel.title) == _id_fragment(category.link_title) and all(
                control.control_type == "page" for control in panel.controls
            ):
                _add_panel_contents(page, panel)

    if page_doc.sections_as_pages:
        _add_feature_guide_links(page, sections, page_doc, targets)
        return ET.ElementTree(page)

    command_context = _share_command_location(page, sections, commands_by_name, command_context)
    for section_doc in sections:
        section = page
        if len(sections) != 1 or section_doc.title != page_doc.title:
            section = _append_child(page, "section")
            section.set("id", _id_fragment(section_doc.title))
            _append_child(section, "title", section_doc.title)
        _add_feature_section_contents(
            section,
            section_doc,
            targets,
            link_text,
            commands_by_name,
            command_context,
            page_doc.page_id,
        )

    if _page_filename(page_doc.page_id) == PREFERENCES_PAGE:
        _add_preferences_guide_links(page, page_doc.topics_title)
    return ET.ElementTree(page)


def build_feature_pages(
    page_docs: list[FeaturePageDoc],
    targets: dict[str, str],
    link_text: dict[str, LinkTextDoc],
    reusable_sections: dict[str, FeatureSectionDoc],
    feature_order: list[str],
    command_groups: list[tuple[str, CollectedCommandGroupDoc]] | None = None,
    preference_links: PreferenceCommandLinks | None = None,
    preference_pages: list[PageDoc] | None = None,
) -> dict[str, str]:
    """Generates Mallard pages for feature and task documentation."""

    if len(feature_order) != len(set(feature_order)):
        raise ValueError("Duplicate feature in feature_order")
    if len({page.page_id for page in page_docs}) != len(page_docs):
        raise ValueError("Duplicate feature page id")
    resolved_sections = {
        page.page_id: _resolve_feature_sections(page, reusable_sections) for page in page_docs
    }
    page_ids = [
        page.page_id for page in page_docs if not page.sections_as_pages or page.generate_guide
    ]
    page_ids.extend(
        _feature_section_page_id(page, section)
        for page in page_docs
        if page.sections_as_pages
        for section in resolved_sections[page.page_id]
    )
    if len(page_ids) != len(set(page_ids)):
        raise ValueError("Duplicate generated feature page id")
    missing = set(page_ids) - set(feature_order)
    unknown = set(feature_order) - set(page_ids)
    if missing or unknown:
        raise ValueError(
            f"Invalid feature_order: missing {sorted(missing)}, unknown {sorted(unknown)}"
        )
    sort_indices = {page_id: index for index, page_id in enumerate(feature_order, start=1)}

    commands_by_name = {
        command.name: command
        for _page_id, group in command_groups or []
        for command in group.commands
        if command.command_type == "keyboard"
    }
    explicit_sections = [section for sections in resolved_sections.values() for section in sections]
    command_context = FeatureCommandContext(
        contents=_command_content_registry(command_groups or []),
        explicit_names={name for section in explicit_sections for name in section.command_names},
        preference_links=preference_links or PreferenceCommandLinks(),
        preference_categories={
            _target_page_id(page.page_id, PREFERENCES_PAGE_PREFIX): page
            for page in preference_pages or []
        },
        preference_panels={
            panel.panel_id: (page, panel)
            for page in preference_pages or []
            for panel in page.panels
        },
    )
    pages: dict[str, ET.ElementTree] = {}
    for page_doc in page_docs:
        if page_doc.sections_as_pages and not page_doc.generate_guide:
            if not page_doc.topics_guide_xref:
                raise ValueError(f"{page_doc.page_id} needs a guide for its topic pages")
        else:
            pages[_page_filename(page_doc.page_id)] = _build_feature_page(
                page_doc,
                sort_indices[page_doc.page_id],
                targets,
                link_text,
                reusable_sections,
                commands_by_name,
                command_context,
            )
        if not page_doc.sections_as_pages:
            continue

        for section_doc in resolved_sections[page_doc.page_id]:
            section_page_id = _feature_section_page_id(page_doc, section_doc)
            pages[_page_filename(section_page_id)] = _build_feature_section_page(
                page_doc,
                section_doc,
                sort_indices[section_page_id],
                targets,
                link_text,
                commands_by_name,
                command_context,
            )
    _add_preferences_directory(pages, preference_pages or [], targets)
    return {filename: _serialize(tree) for filename, tree in pages.items()}


def _add_preferences_directory(
    pages: dict[str, ET.ElementTree], preferences: list[PageDoc], targets: dict[str, str]
) -> None:
    """Links whole feature pages from Preferences, keeping backlinks out of settings sections."""

    if PREFERENCES_PAGE not in pages or not preferences:
        return

    def tree(filename: str) -> ET.Element:
        root = pages[filename].getroot()
        assert root is not None
        return root

    preferences_root = tree(PREFERENCES_PAGE)
    preferences_root.set("version", "1.1")
    directory = preferences_root.find(f"{{{MALLARD_NS}}}section[@id='settings-categories']")
    assert directory is not None
    info = ET.Element(f"{{{MALLARD_NS}}}info")
    directory.insert(0, info)
    groups = []
    for preference in preferences:
        destination = targets[preference.page_id].split("#", 1)[0]
        if destination == preference.page_id:
            continue
        category = _target_page_id(preference.page_id, PREFERENCES_PAGE_PREFIX)
        groups.append(category)
        link = _append_child(info, "link")
        link.attrib.update(type="topic", xref=destination, group=category)
        destination_info = tree(_page_filename(destination)).find(f"{{{MALLARD_NS}}}info")
        assert destination_info is not None
        title = _append_child(destination_info, "title", preference.link_title)
        title.attrib.update(type="link", role="preferences")
        description = destination_info.find(f"{{{MALLARD_NS}}}desc")
        assert description is not None
        description.text = preference.description
    links = directory.find(f"{{{MALLARD_NS}}}links")
    assert links is not None
    links.set("groups", " ".join(groups))
    links.set("role", "preferences")


def _wrap_paragraph_text(text: str, indent: str, width: int = 100, prefix_len: int = 0) -> str:
    """Wraps paragraph text preserving leading and trailing whitespace."""

    if not text or not text.strip():
        return text

    leading = text[: len(text) - len(text.lstrip())]
    trailing = text[len(text.rstrip()) :]
    content = text.strip()
    first_width = max(width - len(indent) - prefix_len, 20)
    subsequent_width = max(width - len(indent), 20)
    first_lines = textwrap.wrap(
        content, width=first_width, break_on_hyphens=False, break_long_words=False
    )
    lines = first_lines[:1]
    if lines:
        remaining = content[len(lines[0]) :].strip()
        if remaining:
            lines.extend(
                textwrap.wrap(
                    remaining,
                    width=subsequent_width,
                    break_on_hyphens=False,
                    break_long_words=False,
                )
            )

    separator = "\n" + indent
    return f"{leading}{separator.join(lines)}{trailing}"


def _wrap_tail_after_inline(text: str, indent: str, prefix_len: int, width: int) -> str:
    """Wraps tail text after an inline element."""

    if not text or not text.strip():
        return text

    trailing = text[len(text.rstrip()) :]
    content = text.strip()
    if content[0] in ",.;:!?)":
        return _wrap_paragraph_text(text, indent, width, prefix_len=prefix_len)
    if len(indent) + prefix_len + len(content.split(maxsplit=1)[0]) > width:
        if content.startswith(": "):
            wrapped = _wrap_paragraph_text(f"{content[2:]}{trailing}", indent, width)
            return f":\n{indent}{wrapped.lstrip()}"
        content = f"\n{indent}{content}{trailing}"
        return _wrap_paragraph_text(content, indent, width)

    return _wrap_paragraph_text(text, indent, width, prefix_len=prefix_len)


def _serialized_inline_length(element: ET.Element) -> int:
    """Returns serialized length of element without its tail."""

    tail = element.tail
    element.tail = None
    try:
        return len(ET.tostring(element, encoding="unicode", short_empty_elements=True))
    finally:
        element.tail = tail


def _add_closing_tag_indent(text: str, indent: str) -> str:
    """Returns text ending with indentation for a separate closing tag line."""

    if not text or not text.strip():
        return text
    return f"{text.rstrip()}\n{indent}"


def _wrap_generated_paragraphs(root: ET.Element, width: int = 96) -> None:
    """Wraps generated paragraph text so serialized Mallard stays readable."""

    def walk(element: ET.Element, depth: int) -> None:
        tag = element.tag.rsplit("}", 1)[-1]
        if tag == "desc" and element.text and element.text.strip():
            closing_indent = "  " * depth
            inline_indent = "  " * (depth + 1)
            element.text = _wrap_paragraph_text(element.text, inline_indent, width)
            element.text = f"\n{inline_indent}{element.text.lstrip()}"
            element.text = _add_closing_tag_indent(element.text, closing_indent)
        if tag == "p":
            closing_indent = "  " * depth
            inline_indent = "  " * (depth + 1)
            element.text = _wrap_paragraph_text(element.text or "", inline_indent, width)
            if element.text and element.text.strip():
                element.text = f"\n{inline_indent}{element.text.lstrip()}"
            for child in element:
                prefix_len = _serialized_inline_length(child)
                child.tail = _wrap_tail_after_inline(
                    child.tail or "",
                    inline_indent,
                    prefix_len,
                    width,
                )
            if len(element):
                element[-1].tail = _add_closing_tag_indent(element[-1].tail or "", closing_indent)
            else:
                element.text = _add_closing_tag_indent(element.text or "", closing_indent)

        for child in element:
            walk(child, depth + 1)

    walk(root, 0)


def _serialize(tree: ET.ElementTree) -> str:
    """Serializes Mallard XML with a generated-file comment."""

    ET.register_namespace("", MALLARD_NS)
    ET.register_namespace("its", ITS_NS)
    tree = copy.deepcopy(tree)
    ET.indent(tree, space="  ")
    root = tree.getroot()
    assert root is not None
    _wrap_generated_paragraphs(root)
    body = ET.tostring(root, encoding="unicode", short_empty_elements=True)
    body = re.sub(r"(<title type=\"link\">)(.*?)(</title>)", r"\1\2\3", body)
    body = re.sub(
        r"(<title>\n\s+)(<media [^>]*/>)\n\s+(<app>Orca</app> [^<]+)</title>",
        r"\1\2 \3\n  </title>",
        body,
    )
    body = re.sub(
        r"(<title>\n\s+)(<media [^>]*/>)\n\s+([^<]+)</title>",
        r"\1\2 \3\n  </title>",
        body,
    )
    body = re.sub(
        r"(<title>\n\s+)(<media [^>]*/>) ([^<]+)</title>",
        r"\1\2 \3\n  </title>",
        body,
    )
    return f"<!--{GENERATED_COMMENT}-->\n{body}\n"


