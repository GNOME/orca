def _modifier_labels(modifiers: int) -> list[str]:
    """Returns modifier labels for keyseq markup."""

    labels = []
    if modifiers & _FAKE_KEYBINDING_CONSTANTS["ORCA_MODIFIER_MASK"]:
        labels.append("Orca Modifier")
    if modifiers & _FAKE_KEYBINDING_CONSTANTS["CTRL_MODIFIER_MASK"]:
        labels.append("Ctrl")
    if modifiers & _FAKE_KEYBINDING_CONSTANTS["ALT_MODIFIER_MASK"]:
        labels.append("Alt")
    if modifiers & _FAKE_KEYBINDING_CONSTANTS["SHIFT_MODIFIER_MASK"]:
        labels.append("Shift")
    return labels


def _keybinding_parts(keybinding: KeyBindingDoc) -> list[str]:
    """Returns key labels for keybinding."""

    return [*_modifier_labels(keybinding.modifiers), _key_label(keybinding.keysym)]


def _click_count_text(click_count: int) -> str:
    """Returns human text for a multi-click keybinding."""

    if click_count == 2:
        return " (press twice)"
    if click_count == 3:
        return " (press three times)"
    if click_count > 1:
        return f" (press {click_count} times)"
    return ""


def _keybindings_equal(first: KeyBindingDoc | None, second: KeyBindingDoc | None) -> bool:
    """Returns True if two keybindings have the same user-facing value."""

    return first == second


def _append_keyseq(parent: ET.Element, keybinding: KeyBindingDoc) -> ET.Element:
    """Appends Mallard keyseq markup for keybinding."""

    keyseq = _append_child(parent, "keyseq")
    for key in _keybinding_parts(keybinding):
        _append_child(keyseq, "key", key)
    keyseq.tail = _click_count_text(keybinding.click_count)
    return keyseq


