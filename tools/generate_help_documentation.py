def _command_group_label(
    tree: ast.Module,
    class_constants: dict[str, dict[str, Any]],
    source_file: str,
) -> str:
    """Returns the owner GROUP_LABEL for get_commands(), if discoverable."""

    function_node = _find_module_function(tree, "get_commands")
    if function_node is not None and function_node.args.args:
        annotation = function_node.args.args[0].annotation
        if isinstance(annotation, ast.Name):
            value = class_constants.get(annotation.id, {}).get("GROUP_LABEL")
            if isinstance(value, str) and value:
                return value

    stem = Path(source_file).stem.removesuffix("_command_definitions")
    return stem.replace("_", " ").capitalize()


def _command_owner_constants(
    tree: ast.Module,
    class_constants: dict[str, dict[str, Any]],
) -> dict[str, Any]:
    """Returns constants for the owner class used by get_commands()."""

    function_node = _find_module_function(tree, "get_commands")
    if function_node is None or not function_node.args.args:
        return {}
    annotation = function_node.args.args[0].annotation
    if isinstance(annotation, ast.Name):
        return class_constants.get(annotation.id, {})
    return {}


def _find_module_function(tree: ast.Module, name: str) -> ast.FunctionDef | None:
    """Returns the top-level function named name."""

    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == name:
            return node
    return None


def _execute_command_definition_module(
    path: Path,
    group_label: str,
    owner_constants: dict[str, Any],
    command_names: dict[str, str],
    braille_names: dict[int, str],
    labels: dict[str, str],
    voice_set: tuple[str, str],
) -> tuple[list[CollectedCommandDoc], SourceCommandGroupDoc]:
    """Executes one command-definition module in a fake Orca package."""

    namespace: dict[str, Any] = {
        "__name__": f"orca.{path.stem}",
        "__file__": str(path),
        "__package__": "orca",
    }
    with _fake_orca_modules(command_names, labels):
        # pylint: disable-next=exec-used
        exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), namespace)  # noqa: S102
        owner_path = path.with_name(path.name.replace("_command_definitions", ""))
        owner_tree = ast.parse(owner_path.read_text(encoding="utf-8"))
        methods = {node.name for node in ast.walk(owner_tree) if isinstance(node, ast.FunctionDef)}
        owner = _FakeCommandOwner(group_label, owner_constants, methods, voice_set)
        if path.stem == "caret_navigator_command_definitions":
            # Include developer-opt-in selection commands in the untranslated preview.
            owner.get_selection_enabled = lambda: True
            owner.get_selection_available = lambda: True
        raw_commands = namespace["get_commands"](owner)
        voice_set_commands = namespace.get("get_voice_set_commands")
        if voice_set_commands is not None:
            raw_commands.extend(voice_set_commands(owner))
        if "get_documentation" not in namespace:
            raise ValueError(f"Missing command metadata provider in {path}")
        group_doc = namespace["get_documentation"]()

    commands: list[CollectedCommandDoc] = []
    for raw_command in raw_commands:
        if not raw_command.is_user_visible():
            continue
        command_type = (
            "braille" if isinstance(raw_command, _COMMAND_MODULE.BrailleCommand) else "keyboard"
        )
        desktop_keybinding = None
        laptop_keybinding = None
        braille_bindings = []
        if command_type == "keyboard":
            desktop_keybinding = _keybinding_doc(raw_command.get_default_keybinding(True))
            laptop_keybinding = _keybinding_doc(raw_command.get_default_keybinding(False))
        else:
            braille_bindings = list(
                dict.fromkeys(
                    braille_names[binding] for binding in raw_command.get_braille_bindings()
                )
            )
        commands.append(
            CollectedCommandDoc(
                name=raw_command.get_name(),
                label=raw_command.get_description(),
                group=raw_command.get_group_label(),
                command_type=command_type,
                braille_bindings=braille_bindings,
                desktop_keybinding=desktop_keybinding,
                laptop_keybinding=laptop_keybinding,
                source_file=str(path),
            )
        )

    if not isinstance(group_doc, SourceCommandGroupDoc):
        raise ValueError(f"Invalid command metadata from {path}")
    return commands, group_doc


def _keybinding_doc(keybinding: Any) -> KeyBindingDoc | None:
    """Returns serializable keybinding metadata."""

    if keybinding is None or not keybinding.keysymstring:
        return None
    return KeyBindingDoc(
        keysym=keybinding.keysymstring,
        modifiers=keybinding.modifiers,
        click_count=keybinding.click_count,
    )


def collect_command_groups(src_dir: Path) -> list[CollectedCommandGroupDoc]:
    """Collects command documentation from command-definition modules."""

    labels = _collect_labels(src_dir)
    command_names = _collect_command_names(src_dir)
    class_constants, module_constants_by_file = _collect_constants(src_dir, labels)
    voice_set = (
        module_constants_by_file["gsettings_registry.py"]["PRIMARY_VOICE_SET"],
        labels["VOICE_SET_GLOBAL"],
    )
    with _fake_orca_modules(command_names, labels):
        braille_path = src_dir / "orca/braille_presenter_command_definitions.py"
        namespace: dict[str, Any] = {"__name__": "orca._braille_names", "__package__": "orca"}
        # pylint: disable-next=exec-used
        exec(  # noqa: S102 - trusted first-party source, not a sandbox
            compile(braille_path.read_text(encoding="utf-8"), str(braille_path), "exec"), namespace
        )
        braille_names = namespace["get_brltty_command_names"]()
    groups_by_title: dict[str, CollectedCommandGroupDoc] = {}

    for path in sorted((src_dir / "orca").glob("*_command_definitions.py")):
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
            group_label = _command_group_label(tree, class_constants, str(path))
            owner_constants = _command_owner_constants(tree, class_constants)
            commands, source_group_doc = _execute_command_definition_module(
                path, group_label, owner_constants, command_names, braille_names, labels, voice_set
            )
        except (OSError, SyntaxError, AttributeError, TypeError, ValueError) as error:
            raise ValueError(f"Cannot collect documentation from {path}: {error}") from error

        group_label = source_group_doc.title or group_label
        metadata_by_name = {command.name: command for command in source_group_doc.commands}
        unmatched = metadata_by_name.keys() - {command.name for command in commands}
        if unmatched:
            raise ValueError(f"{path}: metadata for unknown commands: {sorted(unmatched)}")

        group = groups_by_title.setdefault(
            group_label,
            CollectedCommandGroupDoc(
                title=group_label,
                target=source_group_doc.target,
                link_title=source_group_doc.link_title,
                summary=source_group_doc.summary,
                see_also=source_group_doc.see_also,
                sections=(),
                source_file=str(path),
                since=source_group_doc.since,
            ),
        )
        if source_group_doc.target and not group.target:
            group.target = source_group_doc.target
        if source_group_doc.link_title and not group.link_title:
            group.link_title = source_group_doc.link_title
        if source_group_doc.summary and not group.summary:
            group.summary = source_group_doc.summary
        if source_group_doc.see_also:
            group.see_also = tuple(dict.fromkeys([*group.see_also, *source_group_doc.see_also]))
        if source_group_doc.sections:
            group.sections = (*group.sections, *source_group_doc.sections)
        if source_group_doc.since:
            if group.since and group.since != source_group_doc.since:
                raise ValueError(
                    f"Conflicting introduction releases for command group {group_label!r}"
                )
            group.since = source_group_doc.since

        for command in commands:
            metadata = metadata_by_name.get(command.name)
            if metadata is not None:
                command.summary = metadata.summary
                command.details = metadata.details
                command.since = metadata.since
            group.commands.append(command)

    for group in groups_by_title.values():
        group.commands.sort(key=lambda command: (command.command_type, command.label.casefold()))

    return sorted(groups_by_title.values(), key=lambda group: group.title.casefold())


