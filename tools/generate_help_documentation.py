def _diff(expected: str, actual: str, path: Path) -> str:
    return "".join(
        difflib.unified_diff(
            actual.splitlines(keepends=True),
            expected.splitlines(keepends=True),
            fromfile=str(path),
            tofile=f"{path} (generated)",
        )
    )


def validate_generated_pages(pages: dict[str, str]) -> None:
    """Rejects broken cross-references, invalid item anchors, and unnamed sections."""

    roots = {
        name.removesuffix(".page"): ET.fromstring(content)  # noqa: S314 - generated, trusted XML
        for name, content in pages.items()
    }
    anchors: dict[str, set[str]] = {}
    for page_id, root in roots.items():
        if root.get("type") == "guide" and page_id != "index" and not page_id.endswith("_guide"):
            raise ValueError(f"Guide page id must end in _guide: {page_id}")
        ids = [node.attrib["id"] for node in root.iter() if "id" in node.attrib]
        if len(ids) != len(set(ids)):
            raise ValueError(f"Duplicate anchors in {page_id}")
        anchors[page_id] = set(ids)
        for node in root.iter():
            if node.tag == f"{{{MALLARD_NS}}}item" and "id" in node.attrib:
                raise ValueError(f"Invalid item anchor in {page_id}")
            if node.tag in {f"{{{MALLARD_NS}}}page", f"{{{MALLARD_NS}}}section"}:
                title = node.find(f"{{{MALLARD_NS}}}title")
                if title is None or not "".join(title.itertext()).strip():
                    raise ValueError(f"Missing or empty title in {page_id}")
                seen_section = False
                for child in node:
                    if child.tag == f"{{{MALLARD_NS}}}section":
                        seen_section = True
                    elif seen_section and child.tag != f"{{{MALLARD_NS}}}links":
                        raise ValueError(f"Block content follows a section in {page_id}")
    for page_id, root in roots.items():
        for node in root.iter():
            if "xref" not in node.attrib:
                continue
            xref = node.attrib["xref"]
            destination, _, fragment = xref.partition("#")
            destination = destination or page_id
            if destination not in roots or (fragment and fragment not in anchors[destination]):
                raise ValueError(f"Broken help reference in {page_id}: {xref}")


RegistryValue = TypeVar("RegistryValue")


def _merge_registries(*registries: dict[str, RegistryValue]) -> dict[str, RegistryValue]:
    """Rejects conflicting ownership instead of silently overwriting help targets."""

    combined: dict[str, RegistryValue] = {}
    for registry in registries:
        for target, value in registry.items():
            if target in combined:
                raise ValueError(f"Help target is declared by multiple owners: {target!r}")
            combined[target] = value
    return combined


def main() -> int:
    """CLI entry point."""

    repo_root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description="Generate Orca's uninstalled English help preview")
    parser.add_argument(
        "--src-dir",
        default=str(repo_root / "src"),
        help="Path to Orca src directory.",
    )
    parser.add_argument(
        "--output-dir",
        default=str(repo_root / "help_ng"),
        help="Path to output Mallard directory (default: help_ng; not installed or translated).",
    )
    parser.add_argument(
        "--metadata",
        default=str(repo_root / "help_ng" / "generated_help_metadata.json"),
        help="Path to generated-help prose metadata.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check that generated files match committed files.",
    )
    args = parser.parse_args()

    src_dir = Path(args.src_dir)
    output_dir = Path(args.output_dir)
    metadata_path = Path(args.metadata)

    try:
        metadata = _load_preferences_metadata(metadata_path)
        preference_page_docs = collect_preference_page_docs(src_dir, metadata_path, metadata)
        command_page_groups = collect_command_page_groups(src_dir)
        feature_page_docs, reusable_feature_sections = collect_feature_documentation(src_dir)
        targets = _merge_registries(
            _preference_target_registry(
                preference_page_docs, feature_page_docs, reusable_feature_sections
            ),
            _feature_target_registry(feature_page_docs, reusable_feature_sections),
            _feature_command_targets(
                feature_page_docs,
                reusable_feature_sections,
                command_page_groups,
            ),
        )
        link_text = _merge_registries(
            _preference_link_text_registry(preference_page_docs),
            _command_link_text_registry(command_page_groups),
            _feature_link_text_registry(feature_page_docs, reusable_feature_sections),
        )
        preference_links = _preference_command_links(
            preference_page_docs, command_page_groups, targets, link_text
        )
        generated_pages = {"index.page": _serialize(_build_help_index_page(metadata["index"]))}
        generated_pages.update(
            build_feature_pages(
                feature_page_docs,
                targets,
                link_text,
                reusable_feature_sections,
                metadata["feature_order"],
                command_page_groups,
                preference_links,
                preference_page_docs,
            )
        )
        validate_generated_pages(generated_pages)
    except Exception as error:  # pylint: disable=broad-exception-caught
        print(f"Error generating help documentation: {error}", file=sys.stderr)
        if not isinstance(error, (ValueError, OSError)):
            traceback.print_exception(error)
        return 1

    if args.check:
        unexpected = {path.name for path in output_dir.glob("*.page")} - generated_pages.keys()
        if unexpected:
            print(f"Unexpected help pages: {sorted(unexpected)}", file=sys.stderr)
            return 1
        for filename, content in generated_pages.items():
            output_path = output_dir / filename
            try:
                actual = output_path.read_text(encoding="utf-8")
            except OSError as error:
                print(f"Error reading {output_path}: {error}", file=sys.stderr)
                return 1
            if actual != content:
                print(_diff(content, actual, output_path), file=sys.stderr)
                return 1
        print("Generated help documentation is up to date.", file=sys.stderr)
        return 0

    try:
        output_dir.mkdir(parents=True, exist_ok=True)
        for filename, content in generated_pages.items():
            (output_dir / filename).write_text(content, encoding="utf-8")
        figures = metadata_path.parent / "figures"
        if figures.resolve() != (output_dir / "figures").resolve():
            shutil.copytree(figures, output_dir / "figures", dirs_exist_ok=True)
    except OSError as error:
        print(f"Error writing generated help documentation: {error}", file=sys.stderr)
        return 1

    print(f"Documentation written to {output_dir}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
