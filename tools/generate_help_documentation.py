def _resolve_feature_sections(
    page_doc: FeaturePageDoc,
    reusable_sections: dict[str, FeatureSectionDoc],
) -> tuple[FeatureSectionDoc, ...]:
    """Returns feature sections, replacing section references with reusable sections."""

    sections: list[FeatureSectionDoc] = []
    for section_doc in page_doc.sections:
        if not section_doc.include_target:
            sections.append(section_doc)
            continue
        try:
            reusable = reusable_sections[section_doc.include_target]
            sections.append(
                replace(reusable, since=section_doc.since) if section_doc.since else reusable
            )
        except KeyError as error:
            raise ValueError(
                f"{page_doc.page_id} references unknown feature section "
                f"{section_doc.include_target!r}"
            ) from error
    return tuple(sections)


def _feature_section_page_id(page_doc: FeaturePageDoc, section_doc: FeatureSectionDoc) -> str:
    """Returns the generated page id for a feature section child topic."""

    if not section_doc.topic_id:
        raise ValueError(f"Missing stable topic id for {page_doc.page_id}: {section_doc.title}")
    return f"{page_doc.page_id.removesuffix('_guide')}_{section_doc.topic_id}"


def _feature_target_registry(
    page_docs: list[FeaturePageDoc],
    reusable_sections: dict[str, FeatureSectionDoc],
) -> dict[str, str]:
    """Returns logical feature targets mapped to generated Mallard xrefs."""

    targets: dict[str, str] = {}
    for page_doc in page_docs:
        destination = page_doc.page_id
        if not page_doc.generate_guide and page_doc.sections_as_pages:
            destination = page_doc.topics_guide_xref
        targets[page_doc.page_id] = destination
        if page_doc.target:
            targets[page_doc.target] = destination
        for section_doc in _resolve_feature_sections(page_doc, reusable_sections):
            if section_doc.target:
                if page_doc.sections_as_pages:
                    targets[section_doc.target] = _feature_section_page_id(page_doc, section_doc)
                else:
                    section_id = _id_fragment(section_doc.title)
                    targets[section_doc.target] = f"{page_doc.page_id}#{section_id}"
    return targets


def _feature_link_text_registry(
    page_docs: list[FeaturePageDoc],
    reusable_sections: dict[str, FeatureSectionDoc],
) -> dict[str, LinkTextDoc]:
    """Returns default link text for feature targets."""

    link_text: dict[str, LinkTextDoc] = {}
